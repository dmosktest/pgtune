import {
  formatMemoryKb,
  formatSettingValue,
  type TuneInput,
  type TuneResult,
  type TuneSetting,
} from "./tune";
import type { ManagedTarget } from "./export-formats";

export type BriefContext = {
  input: TuneInput;
  result: TuneResult;
  managed: ManagedTarget;
  localePath: string;
  shareUrl: string;
  exportTab: string;
  confText: string;
};

function settingLines(settings: TuneSetting[]): string {
  return settings
    .map((s) => `- \`${s.key}\` = \`${formatSettingValue(s)}\`${s.restart ? " (restart)" : ""}`)
    .join("\n");
}

function inputBlock(input: TuneInput): string {
  return [
    `- PostgreSQL: ${input.dbVersion}`,
    `- OS: ${input.osType}`,
    `- Profile: ${input.dbType}`,
    `- Host RAM: ${input.totalMemory} ${input.totalMemoryUnit}`,
    `- PG RAM share: ${input.pgRamPercent ?? 100}%`,
    `- CPU: ${input.cpuNum ?? "(auto)"}`,
    `- max_connections (input): ${input.connectionNum ?? "(auto)"}`,
    `- Storage: ${input.hdType}`,
    `- DB size vs RAM: ${input.dbSize}`,
    `- Role: ${input.serverRole ?? "standalone"}`,
    `- Pooler: ${input.poolerMode ?? "none"}`,
    `- Peak complex queries: ${input.peakComplexQueries ?? 2}`,
  ].join("\n");
}

function warningLines(result: TuneResult): string {
  if (!result.warnings.length) return "- (none)";
  return result.warnings.map((w) => `- [${w.level}] ${w.id}`).join("\n");
}

export function formatHumanBrief(ctx: BriefContext): string {
  const b = ctx.result.budget;
  return `# PostgreSQL tuning brief (human / DBA)

Generated by [pgtune](https://pgtune.dmosk.net/) in the browser. Treat as a starting point — verify under real load.

## Share link
${ctx.shareUrl}

## Hardware and workload inputs
${inputBlock(ctx.input)}

## Memory budget
- Host RAM: ${formatMemoryKb(b.hostRamKb)}
- PostgreSQL budget: ${formatMemoryKb(b.pgRamKb)}
- shared_buffers: ${formatMemoryKb(b.sharedBuffersKb)}
- maintenance_work_mem: ${formatMemoryKb(b.maintenanceWorkMemKb)}
- connections × work_mem (peak model): ${formatMemoryKb(b.connectionsWorkMemKb)}
- OS / other: ${formatMemoryKb(b.osCacheKb)}

## Recommended settings
Target platform filter: \`${ctx.managed}\`

${settingLines(ctx.result.settings)}

## Warnings to review
${warningLines(ctx.result)}

## Suggested next steps
1. Apply on a staging instance first (or use ALTER SYSTEM / managed console).
2. Restart only if parameters marked \`restart\` are changed.
3. Watch \`pg_stat_statements\`, checkpoints, temp files, and cache hit ratio.
4. Prefer a pooler over raising \`max_connections\`.
5. Keep the previous config until metrics look healthy.

## Export snippet (${ctx.exportTab})
\`\`\`
${ctx.confText}
\`\`\`
`;
}

export function formatAgentBrief(ctx: BriefContext): string {
  const settingsObj: Record<string, string | number | boolean> = {};
  for (const s of ctx.result.settings) {
    settingsObj[s.key] = s.value;
  }
  const payload = {
    tool: "pgtune",
    version_hint: "browser heuristics",
    share_url: ctx.shareUrl,
    managed_target: ctx.managed,
    input: ctx.input,
    budget: ctx.result.budget,
    settings: settingsObj,
    settings_restart: ctx.result.settings.filter((s) => s.restart).map((s) => s.key),
    warnings: ctx.result.warnings,
    export_tab: ctx.exportTab,
  };

  return `# PostgreSQL tuning task for an AI agent

## Goal
Apply or propose the PostgreSQL configuration below on the target environment. Prefer the smallest safe change set. Do not invent credentials or upload configs to third parties.

## Hard constraints
- Values are heuristics from pgtune (browser-only). They are NOT production-certified.
- Never raise \`max_connections\` blindly; prefer a pooler (PgBouncer).
- Parameters listed under \`settings_restart\` need a restart (or managed reboot).
- Official Docker Postgres image: pass GUCs via \`command: ["postgres","-c","name=value",...]\` — not via env vars.
- Respect managed platform limits when \`managed_target\` is not \`selfhosted\`.

## Acceptance criteria
1. Diff current vs recommended; list restart-required keys separately.
2. Apply non-restart changes first when possible; schedule restart changes.
3. After apply: verify \`SHOW\` values, cache hit ratio, temp files, checkpoints, and no OOM.
4. Roll back using the previous config if error rate or latency regresses.

## Machine-readable context (JSON)
\`\`\`json
${JSON.stringify(payload, null, 2)}
\`\`\`

## Human-readable settings
${settingLines(ctx.result.settings)}

## Export artifact (${ctx.exportTab})
\`\`\`
${ctx.confText}
\`\`\`

## Do not
- Commit secrets into git.
- Set \`fsync=off\` or disable durability to “fix” performance.
- Copy-paste into production without a staging check.
`;
}
